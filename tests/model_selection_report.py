def sm(v):
    if not v:
        return "–"
    if not v.get("model"):
        return "(listed, no file)" if not v.get("hf") else "hf:" + v["hf"]
    return SHORT.get(v["model"], v["model"])


def dl(r):
    if not r["downloads"]:
        return "none"
    if sorted(r["downloads"]) == DEF_URLS:
        return "D3"
    return "+".join(URL2.get(u, u) for u in r["downloads"])


def st(r):
    s = r["status"]
    if s == "ok" and r.get("router_error"):
        return "router exit: " + r["router_error"].split("E srv")[-1].strip()[:60]
    if s == "ok":
        return "ok"
    s = re.sub(r"\x1b\[[0-9;]*m", "", s)
    s = s.replace("error: ", "")
    s = re.sub(r"/\S*/sb/\d+", "<ROOT>", s)
    return "FAIL: " + s[:100]


def par(r, key):
    return "/".join((r["roles"][x] or {}).get(key) or "–" for x in ROLES if r["roles"][x]) or "–"


def mmax(r):
    a = r["argv"]
    return next((a[i + 1] for i, v in enumerate(a) if v == "--models-max" and i + 1 < len(a)), "–")


def lj(r):
    j = r.get("language_json") or {}
    return f"{j.get('locale', '')}/{j.get('mode', '')}" + (f"/swap={j['swapped']}" if j.get("swapped") else "") if j else "–"


def esc(s):
    return str(s).replace("|", "\\|")


def table(head, body):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(esc(c) for c in b) + " |" for b in body]
    return "\n".join(out)


