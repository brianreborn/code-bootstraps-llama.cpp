def sections(p):
    s, cur = {}, None
    for l in (p or "").splitlines():
        l = l.strip()
        if not l or l.startswith(";"):
            continue
        m = re.match(r"\[(.*)\]$", l)
        if m:
            cur = m.group(1); s[cur] = {}; continue
        k, _, v = l.partition("="); s.setdefault(cur, {})[k.strip()] = v.strip()
    return s


